import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const original={n:'Cost & Management Accounting',ch:[{n:'Material Cost',d:[1,0,0]}]};
const context={st:{subs:[original,{n:'Auditing & Ethics',ch:[]},{n:'FM & Strategic Management',ch:[]},{n:'My elective',ch:[]}]},checkpoint(){},save(){},render(){},notify(){}};
vm.createContext(context);
const source=fs.readFileSync('ui/views/dashboard.js','utf8');
vm.runInContext(source.slice(0,source.indexOf('// Today dashboard')),context);
context.selectCaInterGroup('1');
assert.equal(context.dashboardSubjects().length,3);
assert.equal(context.st.subs.length,7);
assert.equal(context.st.subs[0],original);
assert.equal(original.ch[0].d[0],1);
context.selectCaInterGroup('2');
assert.deepEqual(Array.from(context.dashboardSubjects(),x=>x.index),[0,1,2]);
context.st.subs[0].n='My renamed paper';
assert.equal(context.dashboardSubjects().length,3);
context.selectCaInterGroup('1');
assert.equal(context.st.subs.length,7);
context.selectCaInterGroup('all');
assert.equal(context.dashboardSubjects().length,7);
context.selectCaInterGroup('invalid');
assert.equal(context.st.caInterGroup,'all');
console.log('Subject groups: preservation, matching, rename, stable indices and repeated switching passed.');

context.selectCaInterGroup('1');
const group1=Array.from(context.dashboardSubjects(),x=>x.subject);
assert.deepEqual(group1.map(s=>s.ch.length),[15,15,24]);
group1[0].ch[0].d[0]=1;
const savedChapter=group1[0].ch[0];
assert.equal(context.fillGroup1Chapters(),false);
assert.equal(group1[0].ch[0],savedChapter);
group1[0].ch.pop();
context.fillGroup1Chapters();
assert.equal(group1[0].ch.length,14,'Intentional deletions stay deleted');
context.st.subs.push({n:'Advanced Accounting custom',ch:[{n:'My completed chapter',d:[1,1,1]}]});
context.fillGroup1Chapters();
assert.equal(context.st.subs.at(-1).ch.length,1,'Custom lists are not silently expanded');
context.st.cur=context.st.subs.length-1;
context.addGroup1ChapterList();
assert.equal(context.st.subs.at(-1).ch.length,16);
assert.equal(context.st.subs.at(-1).ch[0].d[2],1);
context.addGroup1ChapterList();
assert.equal(context.st.subs.at(-1).ch.length,16,'Repeated import has no duplicates');
console.log('Group 1 chapter templates: counts, history, custom lists, deletions and repeated import passed.');

context.st.focus=[{subject:'Cost & Management Accounting',minutes:30},{subject:'Advanced Accounting',minutes:20},{subject:'Elective',minutes:5}];
context.selectCaInterGroup('1');
assert.deepEqual(Array.from(context.selectedStudyLogs(),l=>l.index),[1]);
context.selectCaInterGroup('2');
assert.deepEqual(Array.from(context.selectedStudyLogs(),l=>l.index),[0]);
context.selectCaInterGroup('all');
assert.equal(context.selectedStudyLogs().length,3);
console.log('Group-scoped study logs preserve original indices and all-subject history.');
